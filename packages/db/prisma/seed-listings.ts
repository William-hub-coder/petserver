async function main() {
  const owner = await prisma.user.findUnique({ where: { phone: '13900000001' } });
  if (!owner) throw new Error('请先 seed 主库（缺少店长 13900000001）');

  // 清理旧 transfer 演示 id
  await prisma.petListing.deleteMany({
    where: { id: { in: ['pl_xfer_1', 'pl_xfer_2', 'pl_xfer_3'] } },
  });

  for (const row of listings) {
    await prisma.petListing.upsert({
      where: { id: row.id },
      update: {
        ...row,
        publisherUserId: owner.id,
        publishedAt: row.status === 'published' ? new Date() : null,
      },
      create: {
        ...row,
        publisherUserId: owner.id,
        publishedAt: row.status === 'published' ? new Date() : null,
      },
    });
  }
  console.log('Seed pet listings OK:', listings.length);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
